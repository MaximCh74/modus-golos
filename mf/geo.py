POINTS_KEY = "geo_points"


def norm(name: str | None) -> str:
    """«г. Усть-Каменогорск, промплощадка» → «усть-каменогорск»: первое слово до запятой, без «г.», «город», «пос.», ё → е."""
    s = re.split(r"[,;(/]", (name or "").strip())[0].strip().lower().replace("ё", "е")
    s = re.sub(r"^(?:г\.?|город|пос\.?|поселок|пгт\.?|с\.|село|мкр\.?)\s+", "", s)
    return re.sub(r"\s+", " ", s).strip(" .")


_INDEX = {norm(k): (k, lat, lng, "KZ") for k, (lat, lng) in KZ.items()} | {norm(k): (k, lat, lng, "RU") for k, (lat, lng) in RU.items()}


def manual_points() -> dict:
    return db.setting(POINTS_KEY) or {}


def lookup(name: str | None) -> dict | None:
    """Город → {name, lat, lng, country, source}; сначала точки администратора, потом справочник и псевдонимы; незнакомый — None."""
    key = norm(name)
    if not key:
        return None
    p = manual_points().get(key)
    if p:
        return {"name": p["name"], "lat": p["lat"], "lng": p["lng"], "country": p.get("country"), "source": "admin"}
    hit = _INDEX.get(key) or _INDEX.get(norm(ALIASES.get(key, ""))) or _INDEX.get(key.replace(" ", "-"))
    if not hit:
        return None
    return {"name": hit[0], "lat": hit[1], "lng": hit[2], "country": hit[3], "source": "dictionary"}


def set_point(name: str, lat: float, lng: float) -> dict:
    key = norm(name)
    if not key:
        raise ValueError("пустое название")
    if not (35 <= lat <= 75 and 15 <= lng <= 180):
        raise ValueError("точка вне Казахстана и России")
    pts = manual_points()
    pts[key] = {"name": (name or "").split(",")[0].strip(), "lat": round(lat, 4), "lng": round(lng, 4)}
    db.set_setting(POINTS_KEY, pts)
    return pts[key]


def remove_point(name: str) -> None:
    pts = manual_points()
    pts.pop(norm(name), None)
    db.set_setting(POINTS_KEY, pts)
