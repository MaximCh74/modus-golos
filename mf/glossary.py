def public() -> dict:
    """Структура для фронта: разделы по порядку и термины с текстами (без служебных полей для промптов)."""
    terms = {k: {"label": t["label"], "hint": t["hint"], "section": t["section"], "also": t.get("also", [])} for k, t in TERMS.items()}
    sections = [{"code": c, "title": title, "terms": [k for k, t in TERMS.items() if t["section"] == c]} for c, title in SECTIONS]
    return {"sections": sections, "terms": terms}


def prompt_text() -> str:
    """Строка для системных промптов ИИ — из тех же записей, что и подсказки интерфейса."""
    parts = []
    for t in TERMS.values():
        ai = t.get("ai")
        if not ai:
            continue
        parts.append(f"«{t['label']}»" if ai is True else ai)
    return "Термины системы — используй только их: " + "; ".join(parts) + "."


def forbidden_stems() -> tuple[str, ...]:
    """Основы запрещённых синонимов (для проверки сводки директора: повтор, затем шаблон)."""
    out: list[str] = []
    for t in TERMS.values():
        for s in t.get("not_stems", []):
            if s not in out:
                out.append(s)
    return tuple(out)


def validate() -> list[str]:
    """Самопроверка словаря: все разделы известны, подсказки короткие и без жаргона."""
    codes = {c for c, _ in SECTIONS}
    bad = []
    for k, t in TERMS.items():
        if t["section"] not in codes:
            bad.append(f"{k}: раздел {t['section']}")
        if not (20 <= len(t["hint"]) <= 240):
            bad.append(f"{k}: длина подсказки {len(t['hint'])}")
        low = (t["label"] + " " + t["hint"]).lower()
        for jargon in ("sla", "кластер", "тикет", "эмбеддинг"):
            if jargon in low:
                bad.append(f"{k}: жаргон «{jargon}»")
    return bad
